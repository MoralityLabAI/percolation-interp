"""E08 *calibration* for holonomy percolation, without Qwen/feature claims.

Run: PYTHONPATH=src python experiments/e08_holonomy_percolation.py
Open ui/godel_globe/index.html to explore the generated demo data offline.
Outputs are synthetic; real E07 edge contacts and common-rank frames must be
supplied separately before estimating VPD holonomy.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from percinterp.holonomy import analyze_connection, frame_edge_transports  # noqa: E402


# Bipartite component/neuron fixture. Two independent loops enter at .37/.68.
SRC = np.array([0, 1, 1, 0, 2, 2, 0])
DST = np.array([3, 3, 4, 4, 4, 5, 5])
ENTRY = np.array([.08, .15, .24, .37, .43, .55, .68])
NODES = [
    {"label": "C0", "kind": "component", "lat": 30, "lon": 10},
    {"label": "C1", "kind": "component", "lat": 24, "lon": 130},
    {"label": "C2", "kind": "component", "lat": 45, "lon": 265},
    {"label": "N0", "kind": "coordinate", "lat": 40, "lon": 70},
    {"label": "N1", "kind": "coordinate", "lat": 35, "lon": 185},
    {"label": "N2", "kind": "coordinate", "lat": 50, "lon": 310},
]


def rotation(deg: float) -> np.ndarray:
    t = np.deg2rad(deg)
    return np.array([[np.cos(t), -np.sin(t)], [np.sin(t), np.cos(t)]])


def tangent_frames() -> np.ndarray:
    """Orthonormal tangent frames on a unit sphere: a synthetic curved bundle."""
    out = []
    north = np.array([0., 0., 1.])
    for node in NODES:
        lat, lon = np.deg2rad([node["lat"], node["lon"]])
        normal = np.array([np.cos(lat) * np.cos(lon), np.cos(lat) * np.sin(lon), np.sin(lat)])
        east = np.cross(north, normal)
        east /= np.linalg.norm(east)
        other = np.cross(normal, east)
        out.append(np.stack([east, other], axis=1))
    return np.stack(out)


def make_fixture(mode: str = "planted", *, epsilon: float = 0.05) -> dict:
    q = np.repeat(np.eye(2)[None], len(SRC), axis=0)
    if mode == "planted":
        q[3] = rotation(45)
        q[6] = rotation(90)
    elif mode == "tangent":
        q, accepted, overlap = frame_edge_transports(tangent_frames(), SRC, DST, min_overlap=0.1)
        assert accepted.all(), f"tangent fixture has unreliable edge: {overlap}"
    elif mode != "flat":
        raise ValueError(f"unknown fixture {mode!r}")
    data = analyze_connection(6, SRC, DST, ENTRY, q, ps=np.linspace(0, 1, 101),
                              n_component_vertices=3, epsilon=epsilon)
    data["nodes"] = NODES
    data["provenance"] = {
        "type": "SYNTHETIC_CALIBRATION", "mode": mode,
        "description": "Six synthetic nodes and seven contacts, not measured Qwen/VPD activations.",
        "frame_source": ("tangent frames on unit sphere" if mode == "tangent"
                         else "explicit SO(2) edge transports"),
    }
    return data


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mode", choices=["planted", "flat", "tangent"], default="planted")
    parser.add_argument("--output", type=Path, default=ROOT / "ui" / "godel_globe" / "demo_data.js")
    parser.add_argument("--epsilon", type=float, default=0.05)
    args = parser.parse_args()
    result = make_fixture(args.mode, epsilon=args.epsilon)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(result, indent=2, allow_nan=False)
    if args.output.suffix == ".js":
        body = "/* Synthetic calibration; generated by experiments/e08_holonomy_percolation.py */\n" \
               "window.PERCINTERP_DATA = " + body + ";\n"
    elif args.output.suffix != ".json":
        parser.error("--output must end in .json or .js")
    args.output.write_text(body, encoding="utf-8")
    print(f"{args.output}: {len(result['loops'])} certified cycles, "
          f"p_H={result['p_h']}, known={result['p_h_known']}, mode={args.mode}")


if __name__ == "__main__":
    main()
